-- 00009_reader.sql — Yonde Reader R0 (Doc 16 §4/§7, Doc 12 step 3.6).
--
-- Two tables:
--   telegram_links   — one row per learner: their Telegram binding.
--                      The APP writes link codes (owner-only RLS below);
--                      the reader-bot edge function claims codes and
--                      reads/writes rows with the service role, which
--                      bypasses RLS. chat_id stays NULL until claimed,
--                      so an unclaimed row is just a pending code.
--   reading_passages — the fitted-passage bank (seeded by
--                      supabase/seed/reading_passages.sql, generated by
--                      scripts/build-reader-bank.mjs). SERVICE-ROLE ONLY:
--                      RLS is enabled and NO client policy exists, so the
--                      anon/authenticated roles can neither read nor
--                      write it through the API — the reader-bot function
--                      is the only reader, and fitting happens there.
--
-- Reading events are NOT a table: they go to metrics_events (00007)
-- with the Reader event types from Doc 16 §8, so this migration also
-- extends that table's type check to admit them.

create table if not exists public.telegram_links (
  user_id uuid primary key references auth.users (id) on delete cascade,
  chat_id bigint unique,
  username text,
  link_code text unique,
  link_expires_at timestamptz,
  morning_time time not null default '07:30',
  tz text not null default 'Asia/Tokyo',
  linked_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.telegram_links enable row level security;

drop policy if exists "users own telegram link" on public.telegram_links;
create policy "users own telegram link"
  on public.telegram_links
  for all to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create table if not exists public.reading_passages (
  id text primary key,
  band text not null check (band in ('N5', 'N4', 'N3', 'N2', 'N1')),
  topic text not null default '',
  text text not null,
  -- [{ s, h, l }] — token surface, dictionary headword, deck level
  -- (Doc 16 §5 amendment, 2026-11-06). The surfaces join back into
  -- `text` exactly (the seed script asserts this); the fitting core
  -- matches tokens to the learner's known set by headword.
  tokens jsonb not null default '[]'::jsonb,
  -- [{ word, reading, meaning, h }] — dictionary words in the passage
  -- at or above its band, with their resolved headword `h`; the bot
  -- intersects these with the learner's unknown set (by headword) at
  -- send time, so this list is band-level, never per-learner.
  new_word_candidates jsonb not null default '[]'::jsonb,
  source text not null default 'bank' check (source in ('bank', 'scene')),
  created_at timestamptz not null default now()
);

create index if not exists reading_passages_band_idx
  on public.reading_passages (band);

alter table public.reading_passages enable row level security;
-- No policies on purpose: service-role only (see header comment).

-- Reader event types (Doc 16 §8) join the gate-metrics event family.
-- passage_sent / word_mined are written by reader-bot from R0;
-- reading_opened / passage_completed / word_tapped arrive with the R1
-- Mini App; shadow_* with R2. Admitting them all now keeps later stages
-- migration-free.
alter table public.metrics_events drop constraint if exists metrics_events_type_check;
alter table public.metrics_events
  add constraint metrics_events_type_check
  check (type in (
    'session_completed', 'diagnosis_completed', 'call_outcome', 'effort_check',
    'passage_sent', 'reading_opened', 'passage_completed', 'word_tapped',
    'word_mined', 'shadow_attempted', 'shadow_scored'
  ));
