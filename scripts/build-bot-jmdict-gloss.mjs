// Build the reader-bot's JMdict compound supplement
// (supabase/functions/reader-bot/jmdict-gloss.ts).
//
// Why: the readings block (Doc 16 amendments #9/#13) glosses
// words from DECK_GLOSS — the JLPT deck. But the segmenter can
// split a real compound the deck does not carry as a headword
// (面談 became 面 + 談のお…), and the block then shows a fragment
// or nothing. JMdict's common entries know these compounds.
// This supplement carries ONLY written forms of 2–4 kanji that
// DECK_GLOSS does not already know, as [reading, first gloss]
// pairs — a display lookup for the readings block, nothing else.
//
// Source: the wordsdb build cache (jmdict-eng-common, JMdict —
// EDRDG, CC BY-SA; credited on the app's Sources screen).
// Run: node scripts/build-bot-jmdict-gloss.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '..')
const cachePath = resolve(here, '../../../wordsdb-cache/jmdict-eng-common-3.6.2.json')
const glossPath = resolve(repo, 'supabase/functions/reader-bot/gloss.ts')
const outPath = resolve(repo, 'supabase/functions/reader-bot/jmdict-gloss.ts')

const glossSrc = readFileSync(glossPath, 'utf8')
const deck = JSON.parse(glossSrc.slice(glossSrc.indexOf('= {') + 2, glossSrc.lastIndexOf('}') + 1))
const deckForms = new Set(Object.keys(deck))

const dict = JSON.parse(readFileSync(cachePath, 'utf8'))
const words = dict.words ?? dict
const KANJI_FORM = /^[一-鿿々〆ヶ]{2,4}$/

const out = {}
for (const w of words) {
  const kana = w.kana?.[0]?.text
  if (!kana) continue
  let gloss = ''
  for (const s of w.sense ?? []) {
    if (s.gloss?.length) { gloss = s.gloss[0].text; break }
  }
  if (!gloss) continue
  for (const form of w.kanji ?? []) {
    const text = form.text
    if (!KANJI_FORM.test(text)) continue
    if (deckForms.has(text) || out[text]) continue
    out[text] = [kana, gloss]
  }
}

const header = `// GENERATED by scripts/build-bot-jmdict-gloss.mjs — do not edit by hand.
// JMdict compound supplement for the readings block (Doc 16
// amendment #14): written forms of 2–4 kanji from JMdict's common
// entries (EDRDG, CC BY-SA) that DECK_GLOSS does not carry, as
// [reading, first gloss]. Display lookup only.
export const JMDICT_COMPOUNDS = `
writeFileSync(outPath, header + JSON.stringify(out) + '\n')
console.log(`jmdict-gloss.ts: ${Object.keys(out).length} compounds written`)
