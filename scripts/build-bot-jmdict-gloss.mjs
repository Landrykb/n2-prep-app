// Build the reader-bot's JMdict word supplement
// (supabase/functions/reader-bot/jmdict-gloss.ts).
//
// Why: the readings block (Doc 16 amendments #9/#13) glosses
// words from DECK_GLOSS — the JLPT deck. But the segmenter can
// split a real word the deck does not carry as a headword
// (面談 became 面 + 談のお…), and the block then shows a fragment
// or nothing. JMdict's common entries know these words. This
// supplement carries written forms DECK_GLOSS does not already
// know, as [reading, first gloss] pairs — a display lookup for
// the readings block, nothing else.
//
// Amendment #35 (2026-11-20): the forms widen from pure-kanji
// compounds (2–4 kanji) to any kanji-bearing word of 2–6
// characters — kanji+kana words like 温かい and 手作り shred the
// same way compounds did — and the file gains JMDICT_READINGS_ALT:
// every reading JMdict knows for each deck/supplement word that
// has more than one, so the block can show the other readings
// beside the one used in the text (Landry's two-readings rule).
//
// Source: the wordsdb build cache (jmdict-eng-common, JMdict —
// EDRDG, CC BY-SA; credited on the app's Sources screen).
// Run: node scripts/build-bot-jmdict-gloss.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '..')
const cachePath = resolve(here, '../../../wordsdb-cache/jmdict-eng-common-3.6.2.json')
const glossPath = resolve(repo, 'supabase/functions/reader-bot/gloss.ts')
const outPath = resolve(repo, 'supabase/functions/reader-bot/jmdict-gloss.ts')

const glossSrc = readFileSync(glossPath, 'utf8')
const deck = JSON.parse(glossSrc.slice(glossSrc.indexOf('= {') + 2, glossSrc.lastIndexOf('}') + 1))
const deckForms = new Set(Object.keys(deck))

const dict = JSON.parse(readFileSync(cachePath, 'utf8'))
const words = dict.words ?? dict
const WORD_FORM = /^[一-鿿々〆ヶぁ-ゖァ-ヺー]{2,6}$/
const HAS_KANJI = /[一-鿿]/

const out = {}
for (const w of words) {
  const kana = w.kana?.[0]?.text
  if (!kana) continue
  let gloss = ''
  for (const s of w.sense ?? []) {
    if (s.gloss?.length) { gloss = s.gloss[0].text; break }
  }
  if (!gloss) continue
  for (const form of w.kanji ?? []) {
    const text = form.text
    if (!WORD_FORM.test(text) || !HAS_KANJI.test(text)) continue
    if (deckForms.has(text) || out[text]) continue
    out[text] = [kana, gloss]
  }
}

// Alternate readings: for every word the block can resolve (deck
// or supplement), all the readings JMdict gives that written
// form, in JMdict's order. Only words with more than one reading
// are carried — the block shows them beside the used reading.
// This pass reads the FULL JMdict, not the common subset: the
// common subset files 町 under まち only, and ちょう — the very
// reading the voice note wrongly picked — is exactly the kind of
// second reading the rule exists to surface. A kana's
// appliesToKanji restriction is honoured, so a reading belonging
// to a different written form of the entry never leaks in.
const fullDict = JSON.parse(readFileSync(resolve(here, '../../../wordsdb-cache/jmdict-eng-3.6.2.json'), 'utf8'))
const fullWords = fullDict.words ?? fullDict
const wanted = new Set([...deckForms, ...Object.keys(out)])
const readingsByForm = new Map()
for (const w of fullWords) {
  const forms = (w.kanji ?? []).map((k) => k.text).filter((t) => wanted.has(t))
  if (!forms.length) continue
  for (const kana of w.kana ?? []) {
    if (!kana.text) continue
    const applies = Array.isArray(kana.appliesToKanji) && kana.appliesToKanji.length && !kana.appliesToKanji.includes('*')
      ? kana.appliesToKanji
      : forms
    for (const text of applies) {
      if (!wanted.has(text)) continue
      if (!readingsByForm.has(text)) readingsByForm.set(text, [])
      const list = readingsByForm.get(text)
      if (!list.includes(kana.text)) list.push(kana.text)
    }
  }
}
const alts = {}
for (const [text, list] of readingsByForm) {
  if (list.length > 1) alts[text] = list.slice(0, 4)
}

const header = `// GENERATED by scripts/build-bot-jmdict-gloss.mjs — do not edit by hand.
// JMdict word supplement for the readings block (Doc 16 amendments
// #14 + #35): kanji-bearing written forms of 2–6 characters from
// JMdict's common entries (EDRDG, CC BY-SA) that DECK_GLOSS does
// not carry, as [reading, first gloss]; plus JMDICT_READINGS_ALT —
// every reading of each resolvable word that has more than one.
// Display lookup only.
export const JMDICT_COMPOUNDS = ${JSON.stringify(out)}
export const JMDICT_READINGS_ALT = ${JSON.stringify(alts)}
`
writeFileSync(outPath, header)
console.log(`jmdict-gloss.ts: ${Object.keys(out).length} words, ${Object.keys(alts).length} with alternate readings`)
