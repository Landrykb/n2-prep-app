import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { kanjiLessons } from '../src/data.js'
import { bjtPassages, bjtListening } from '../src/data/bjt.js'
import { n2Listening } from '../src/data/n2Listening.js'
import pkg from 'kanji'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const outPath = path.join(__dirname, '../src/lib/kanjiReadings.js')

function isCJK(char) {
  const cp = char.codePointAt(0)
  return (
    (cp >= 0x4e00 && cp <= 0x9fff) ||
    (cp >= 0x3400 && cp <= 0x4dbf) ||
    (cp >= 0xf900 && cp <= 0xfaff) ||
    (cp >= 0x20000 && cp <= 0x2ebef)
  )
}

function getChars(text) {
  return [...new Set(Array.from(text).filter(isCJK))]
}

const map = new Map()

// Seed from kanjiLessons
for (const item of kanjiLessons) {
  if (item.char) {
    map.set(item.char, { on: item.on || '', kun: item.kun || '' })
  }
}

// Collect all CJK from app content
const texts = []
for (const p of bjtPassages) {
  texts.push(p.text, ...p.questions.flatMap((q) => [q.prompt, ...q.options.map((o) => o.label)]))
}
for (const l of bjtListening) {
  texts.push(l.script, ...l.questions.flatMap((q) => [q.prompt, ...q.options.map((o) => o.label)]))
}
for (const l of n2Listening) {
  texts.push(l.script, ...l.questions.flatMap((q) => [q.prompt, ...q.options.map((o) => o.label)]))
}

const missing = new Set()
for (const t of texts) {
  for (const char of getChars(t)) {
    if (!map.has(char)) missing.add(char)
  }
}

for (const char of missing) {
  try {
    const r = pkg.readings(char)
    const on = r?.on ? r.on.join('・') : ''
    const kun = r?.kun ? r.kun.join('・') : ''
    if (on || kun) map.set(char, { on, kun })
  } catch {}
}

const entries = [...map.entries()].sort((a, b) => a[0].codePointAt(0) - b[0].codePointAt(0))

const lines = [
  '// Fallback common-kanji readings for visual breakdown when the item is not in the main deck.',
  "// Auto-generated by scripts/build-kanji-readings.mjs; edit the script, not this file, for bulk updates.",
  "// KanjiLessons are merged first; kanji package fills remaining characters found in BJT / N2 listening texts.",
  'export const kanjiReadings = {',
]
for (const [char, { on, kun }] of entries) {
  lines.push(`  ${JSON.stringify(char)}: { on: ${JSON.stringify(on)}, kun: ${JSON.stringify(kun)} },`)
}
lines.push('}')

fs.writeFileSync(outPath, lines.join('\n') + '\n')
console.log(`Wrote ${entries.length} kanji readings to ${outPath}`)
