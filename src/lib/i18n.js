// Yonde's UI language system (Doc 20) — pure catalogs + lookup,
// node-tested in tests/i18n.test.mjs.
//
// THE RULES (Landry's locked language spec):
//   - The catalogs translate CHROME only: headings, buttons, labels,
//     hints, footers, empty states. Learning CONTENT (passages,
//     lesson data, dictionary meanings) is data and is never routed
//     through here — the data already carries its own languages.
//   - Coverage is COMPLETE per surface: every key exists in all
//     three catalogs with a non-empty string. tests/i18n.test.mjs
//     enforces exact key parity — a missing key fails the suite.
//   - t() falls back to English for an unknown key, and to the key
//     itself when even English lacks it. The fallback is a safety
//     net for a bad deploy, never a coverage strategy.
//   - Interpolation is {name} placeholders, substituted from vars;
//     a missing var leaves the placeholder visible (honest, greppable)
//     rather than printing "undefined".
//
// Keys are flat and namespaced by surface: shell.*, today.*,
// queue.*, reader.*, lessons.*, parts.* (component search), modal.*,
// lens.*, twin.*, loop.*, call.*, sources.*, auth.*, settings.*,
// problem.* (onboarding chrome on Today), progress.* (ProgressCard),
// notify.* (NotificationCard), feedback.* (FeedbackBox).

