/** Resolve a UI language id to a catalog id (unknown → English). */
export function catalogId(lang) {
  return Object.prototype.hasOwnProperty.call(CATALOGS, lang) ? lang : DEFAULT_LANGUAGE
}

/**
 * Translate `key` for `lang`, substituting {name} placeholders from
 * `vars`. Falls back to English, then to the key itself.
 */
export function t(lang, key, vars = {}) {
  const id = catalogId(lang)
  const raw = CATALOGS[id][key] ?? CATALOGS[DEFAULT_LANGUAGE][key] ?? key
  return String(raw).replace(/\{(\w+)\}/g, (m, name) =>
    vars != null && Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m,
  )
}
